export const CATALOGUE_COPY_KEYS = ["nav", "eyebrow", "title", "lead", "edition", "file", "download", "insideTitle", "chapters", "matrix", "metaDescription", "heroTitle", "heroLead", "heroEcosystem", "heroChoose", "heroCatalogue", "heroPartner"];

/** The catalogue copy of one locale; throws when a translation is missing or incomplete. */
export function catalogueCopy(locale) {
  const row = rows[locale];
  if (!row) throw new Error(`Missing catalogue copy: ${locale}`);
  for (const k of CATALOGUE_COPY_KEYS) {
    const v = row[k];
    const ok = k === "chapters" ? Array.isArray(v) && v.length === 6 && v.every((x) => typeof x === "string" && x.trim()) : typeof v === "string" && v.trim();
    if (!ok) throw new Error(`Incomplete catalogue copy: ${locale}.${k}`);
  }
  return row;
}

/** Fill {placeholders} from a record of values. */
export function fill(template, values) {
  return template.replace(/\{(\w+)\}/g, (m, k) => (k in values ? String(values[k]) : m));
}

