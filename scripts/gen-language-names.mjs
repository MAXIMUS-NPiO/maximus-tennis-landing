/**
 * Writes data/language-names.js: the name of every language of the site in every language of the
 * site (48 × 48), and the names of the two regions the language menu groups them by, from the
 * Unicode CLDR data that ships with Node. The file is committed, so the menu reads the same names
 * on every build and in every browser; regenerate it after adding a language:
 *   node scripts/gen-language-names.mjs
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
const { site } = await import("../data/site.js");

// The code CLDR names each language under (the site's own codes, without script or country).
const CLDR = { sr: "sr", az: "az", uz: "uz", kk: "kk", zh: "zh", pt: "pt", fil: "fil", no: "no" };
const code = (l) => CLDR[l] || l;
// The menu groups languages by the region they are mostly spoken in (UN M49: 150 Europe, 142 Asia).
export const REGION_OF = Object.fromEntries(site.locales.map((l) => [l, ["ar", "tr", "az", "uz", "kk", "hi", "id", "fil", "th", "ja", "ko", "zh"].includes(l) ? "asia" : "europe"]));

const upperFirst = (s, ui) => (s ? s.charAt(0).toLocaleUpperCase(ui) + s.slice(1) : s);
const names = {};
const regions = {};
const fallbacks = [];
const en = new Intl.DisplayNames(["en"], { type: "language" });
for (const ui of site.locales) {
  const dn = new Intl.DisplayNames([code(ui)], { type: "language", fallback: "code" });
  const rn = new Intl.DisplayNames([code(ui)], { type: "region", fallback: "code" });
  const resolved = dn.resolvedOptions().locale.split("-")[0];
  const supported = resolved === code(ui).split("-")[0];
  names[ui] = {};
  for (const l of site.locales) {
    let n = supported ? dn.of(code(l)) : null;
    if (!n || n === code(l)) { n = en.of(code(l)); fallbacks.push(`${ui}:${l}`); }
    names[ui][l] = upperFirst(n, code(ui));
  }
  regions[ui] = supported
    ? { europe: upperFirst(rn.of("150"), code(ui)), asia: upperFirst(rn.of("142"), code(ui)) }
    : { europe: "Europe", asia: "Asia" };
}

const header = "/*! © 2026 Maximus Kiriyakulov. All rights reserved. Proprietary: no licence is granted. */\n" +
  "// Generated by scripts/gen-language-names.mjs from the Unicode CLDR data in Node — do not edit by hand.\n";
const body = `export const regionOf = ${JSON.stringify(REGION_OF)};\n` +
  `export const regionNames = ${JSON.stringify(regions)};\n` +
  `export const languageNames = ${JSON.stringify(names)};\n`;
writeFileSync(path.join(process.cwd(), "data", "language-names.js"), header + body);
console.log(`language names written: ${site.locales.length} × ${site.locales.length}; fell back to English for ${fallbacks.length}: ${fallbacks.slice(0, 40).join(" ")}`);
