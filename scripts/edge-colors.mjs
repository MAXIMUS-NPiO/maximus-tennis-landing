/**
 * Edge colours of the site's photographs — what lets a picture emerge from the black page.
 *
 * For every photograph registered in data/media.js → media, this reads the outer ring of the file
 * (1.5% of each side) and records its average colour. The page then lays a soft matte of exactly
 * that colour beneath the picture, so the picture's boundary has nothing to show against, and the
 * matte — never the picture — fades out into the black. No pixel of a photograph is changed.
 *
 * Usage: node scripts/edge-colors.mjs   (rewrites data/mediaEdges.js; run after adding a photograph)
 */
import sharp from "sharp";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const src = readFileSync(path.join(root, "data", "media.js"), "utf8");
const imports = Object.fromEntries([...src.matchAll(/import (\w+) from "\.\.\/public\/(media\/[^"]+)";/g)].map((m) => [m[1], m[2]]));
const block = src.slice(src.indexOf("export const media = {"), src.indexOf("};", src.indexOf("export const media = {")));
const entries = [...block.matchAll(/^\s+(\w+): owner\((\w+),/gm)].map((m) => [m[1], m[2]]);

const out = {};
for (const [key, imp] of entries) {
  const file = path.join(root, "public", imports[imp]);
  const { data, info } = await sharp(file).removeAlpha().raw().toBuffer({ resolveWithObject: true });
  const { width: w, height: h, channels: c } = info;
  const bw = Math.max(2, Math.round(w * 0.015));
  const bh = Math.max(2, Math.round(h * 0.015));
  let r = 0, g = 0, b = 0, n = 0;
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      if (x >= bw && x < w - bw && y >= bh && y < h - bh) continue;
      const i = (y * w + x) * c;
      r += data[i]; g += data[i + 1]; b += data[i + 2]; n++;
    }
  }
  const hex = (v) => Math.round(v / n).toString(16).padStart(2, "0");
  out[key] = `#${hex(r)}${hex(g)}${hex(b)}`;
}

const body = Object.entries(out).map(([k, v]) => `  ${k}: "${v}",`).join("\n");
writeFileSync(path.join(root, "data", "mediaEdges.js"),
`/**
 * Average colour of the outer ring (1.5% of each side) of each photograph in data/media.js.
 * Generated by scripts/edge-colors.mjs — do not edit by hand; re-run it after adding a photograph.
 */
export const edges = {
${body}
};
`);
console.log(`edge colours written for ${Object.keys(out).length} photographs`);
for (const [k, v] of Object.entries(out)) console.log(`  ${k.padEnd(18)} ${v}`);
