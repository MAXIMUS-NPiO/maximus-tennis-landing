function shape(a, b, path) {
  if (Array.isArray(a)) {
    if (!Array.isArray(b) || b.length !== a.length) throw new Error(`grip shape copy: ${path} has the wrong length`);
    a.forEach((x, i) => shape(x, b[i], `${path}[${i}]`));
  } else if (a && typeof a === "object") {
    if (!b || typeof b !== "object" || Array.isArray(b)) throw new Error(`grip shape copy: ${path} is not an object`);
    for (const k of Object.keys(a)) shape(a[k], b[k], `${path}.${k}`);
    for (const k of Object.keys(b)) if (!(k in a)) throw new Error(`grip shape copy: ${path}.${k} is not in the English master`);
  } else if (typeof b !== "string" || !b.trim()) throw new Error(`grip shape copy: ${path} is empty`);
}

